-- ############################################################################
-- SECTION 7 — Row Level Security
--
-- The browser holds only the anon key. It may READ published content, and it
-- may INSERT a lead (that is what the contact forms do) — nothing else. Every
-- admin write goes through the server with the service-role key, which
-- bypasses RLS entirely.
-- ############################################################################

