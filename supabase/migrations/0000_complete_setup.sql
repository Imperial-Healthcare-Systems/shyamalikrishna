create policy "public read job_categories"   on public.job_categories   for select to anon, authenticated using (active);
create policy "public read job_locations"    on public.job_locations    for select to anon, authenticated using (active);
create policy "public read employment_types" on public.employment_types for select to anon, authenticated using (active);
create policy "public read job_location_map" on public.job_location_map for select to anon, authenticated using (true);

-- Published and closed jobs are public; a DRAFT never is. A closed vacancy has
-- to stay readable so its old URL can say "no longer accepting applications"
-- instead of 404-ing on someone who followed a link.
create policy "public read jobs" on public.jobs
  for select to anon, authenticated
  using (status in ('published', 'closed'));

-- Public insert ---------------------------------------------------------------
-- The callback / enquiry / service forms write here with the anon key. INSERT
-- only: a visitor must never be able to read anyone else's enquiry back out.
drop policy if exists "public insert leads" on public.leads;
create policy "public insert leads" on public.leads for insert to anon, authenticated with check (true);

-- No policies at all for: job_applications, lead_notes, admin_sessions,
-- admin_activity, admin_credentials, admin_password_resets.
-- RLS on + no policy = the anon key sees and writes nothing. Applications are
-- written by POST /api/careers/apply, which verifies the job server-side first.
revoke all on public.job_applications from anon;

