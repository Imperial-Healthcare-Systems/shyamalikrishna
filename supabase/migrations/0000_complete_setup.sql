-- Run this ONE file in the Supabase SQL Editor. It works in both situations:
--
--   A) A BRAND NEW, EMPTY project  -> creates every table the site needs.
--   B) The EXISTING project        -> creates only what is missing and adds
--                                     the recruitment columns to the tables
--                                     that already exist.
--
-- It is fully idempotent and non-destructive: every statement is
-- "if not exists" or "on conflict do nothing". It never drops a table, never
-- deletes a row, and is safe to run twice.
--
-- AFTER running this on a NEW project, load your content with:
--     supabase/seed/0002_data_export.sql
-- (generated by `npm run export-data` from the old project)
-- ============================================================================

